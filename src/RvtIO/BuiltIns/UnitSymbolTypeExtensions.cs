        Symbols.TryGetValue(unitSymbol, out unitSymbolString);

    /// <summary>
    /// Finds the symbol type for <paramref name="unitSymbolString"/>. The text must match a known symbol exactly;
    /// the key returned is the first one whose symbol matches ignoring case.
    /// </summary>
    public static bool TryGetFromSymbol(this string unitSymbolString, out UnitSymbolType unitSymbol)
    {
        unitSymbol = UnitSymbolType.UST_NONE;
        if (!Symbols.ContainsValue(unitSymbolString))
            return false;
        foreach (var kv in Symbols)
        {
            if (kv.Value.Equals(unitSymbolString, StringComparison.OrdinalIgnoreCase))
            {
                unitSymbol = kv.Key;
                break;
            }
        }
        return true;
    }
