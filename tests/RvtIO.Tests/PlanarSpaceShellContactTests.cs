    [Theory]
    [InlineData(0, false)]
    [InlineData(1, false)]
    [InlineData(2, false)]
    [InlineData(0, true)]
    [InlineData(1, true)]
    [InlineData(2, true)]
    public void CompleteConnectedBoundary_WithFourFacesAtOneEdge_IsNotAnExactShell(
        int axis, bool reverse)
    {
        var boundary = Boundary(axis, reverse);
        var faces = boundary.Faces;
        var indices = boundary.BrepSolids![0].FaceIndices;
        string before = JsonSerializer.Serialize(boundary);
        var uses = EdgeUses(faces);
        Assert.Equal(78, uses.Count(pair => pair.Value.Count == 2));
        Assert.Equal(4, Assert.Single(uses, pair => pair.Value.Count != 2).Value.Count);

        // The failure is not explained by two disconnected components or missing faces.
        var visited = new HashSet<int> { 0 };
        var queue = new Queue<int>();
        queue.Enqueue(0);
        while (queue.TryDequeue(out int current))
            foreach (var edge in uses.Values.Where(edge => edge.Count == 2 && edge.Contains(current)))
                foreach (int other in edge)
                    if (visited.Add(other)) queue.Enqueue(other);
        Assert.Equal(29, visited.Count);
        Assert.True(boundary.BrepSolids[0].IsClosed); // source declaration alone is insufficient
        Assert.False(IfcExporter.IsExactFacetedShell(faces, indices));
        Assert.False(IfcExporter.TryOrientExactFacetedShell(faces, indices, out var oriented));
        Assert.Empty(oriented);
        Assert.Equal(before, JsonSerializer.Serialize(boundary));
    }

    [Fact]
    public void DeclaredClosedContactBoundary_PreservesSpaceWithoutInventingBody()
    {
        var boundary = Boundary(0, false);
        string before = JsonSerializer.Serialize(boundary);
        var info = new RevitFileInfo
        {
            Elements =
            [
                new Element
                {
                    Id = 900, Name = "Level", IsNativeLevel = true,
                    SerializedFamilyId = -1, SerializedUnplacedOwnerId = -1,
                    SerializedOwnerDbViewId = -1,
                    Parameters =
                    [
                        new Parameter { Id = -1007102, StorageType = StorageType.Double, Value = 0.0 },
                        new Parameter { Id = -1007111, StorageType = StorageType.Integer, Value = 1 },
                    ],
                },
                new Element
                {
                    Id = 2766296, CategoryId = -2000160, Name = "Contact",
                    SerializedSpaceBoundary = boundary,
                    Parameters =
                    [
                        new Parameter { Id = -1006916, StorageType = StorageType.ElementId, Value = 900 },
                        new Parameter { Id = -1006901, StorageType = StorageType.String, Value = "1.59" },
                    ],
                },
            ],
        };
        using var output = new StringWriter();
        new IfcExporter().Export(info, output);
        string ifc = output.ToString();
        string space = Assert.Single(ifc.Split('\n'), line => line.Contains("=IFCSPACE("));
        Assert.Equal("$", space[(space.IndexOf('(') + 1)..].Split(',')[6]);
        Assert.Contains("=IFCSPACETYPE(", ifc);
        Assert.DoesNotContain("=IFCFACETEDBREP(", ifc);
        Assert.DoesNotContain("=IFCCLOSEDSHELL(", ifc);
        Assert.DoesNotContain("=IFCFACEBASEDSURFACEMODEL(", ifc);
        Assert.Equal(before, JsonSerializer.Serialize(boundary));
    }

    private static Dictionary<((long X, long Y, long Z) A, (long X, long Y, long Z) B),
        List<int>> EdgeUses(IReadOnlyList<GeoFace> faces)
    {
        static (long X, long Y, long Z) Key(double[] point) =>
            ((long)Math.Round(point[0] * .3048 / 1e-5),
             (long)Math.Round(point[1] * .3048 / 1e-5),
             (long)Math.Round(point[2] * .3048 / 1e-5));
        var uses = new Dictionary<((long, long, long), (long, long, long)), List<int>>();
        for (int face = 0; face < faces.Count; face++)
        {
            var ring = faces[face].OuterVertices!;
            for (int i = 0; i < ring.Count; i++)
            {
                var a = Key(ring[i]);
                var b = Key(ring[(i + 1) % ring.Count]);
                Assert.NotEqual(a, b);
                var edge = a.CompareTo(b) < 0 ? (a, b) : (b, a);
                if (!uses.TryGetValue(edge, out var owners)) uses[edge] = owners = [];
                owners.Add(face);
            }
        }
        return uses;
    }

